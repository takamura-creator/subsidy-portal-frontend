const formatList = (items: string[] | undefined): string => {
  if (!items || items.length === 0) return "（未選択）";
  return items.map((s) => `・${s}`).join("\n");
};

const formatListInline = (items: string[] | undefined): string => {
  if (!items || items.length === 0) return "（未選択）";
  return items.join("、");
};

